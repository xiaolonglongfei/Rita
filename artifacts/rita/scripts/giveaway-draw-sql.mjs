// Node 24 strips the shared module's TypeScript types; no extra runtime needed.
// Print regenerated SQL, or use --check to catch UI/draw-definition drift.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GIVEAWAY_MAX_ENTRIES, getGiveawayReviewFilters } from "../lib/giveaway.ts";

const operators = { eq: "=", gte: ">=", lt: "<", lte: "<=" };
const optIn = "u.giveaway_opt_in_at";
const cutoff = "s.entry_cutoff_at";
const conditions = getGiveawayReviewFilters(optIn, cutoff).map(({ column, operator, value }) => {
  const sqlValue = [optIn, cutoff].includes(value) ? value : `'${value.replaceAll("'", "''")}'`;
  return `    AND r.${column} ${operators[operator]} ${sqlValue}`;
}).join("\n");

export const sql = `-- Generated by: node scripts/giveaway-draw-sql.mjs
-- Check shared UI/draw definition: node scripts/giveaway-draw-sql.mjs --check
-- Run at drawing time. Set entry_cutoff_at to the advertised cutoff if earlier.
-- Saved, still-approved reviews passed Layer 1; instructor verification is NOT required.
-- Deleted/rejected reviews do not count. Alternate-method (emailed) entries
-- are added to the pool manually at draw time.
WITH settings AS (
  SELECT ${GIVEAWAY_MAX_ENTRIES}::INTEGER AS giveaway_max_entries, -- GIVEAWAY_MAX_ENTRIES in lib/giveaway.ts
         NOW() AS entry_cutoff_at
),
qualifying_reviews AS (
  SELECT u.id AS user_id, u.email, u.giveaway_opt_in_at, r.id AS review_id
  FROM public.users AS u
  JOIN public.reviews AS r ON r.student_id = u.id
  CROSS JOIN settings AS s
  WHERE u.giveaway_opt_in_at IS NOT NULL
${conditions}
)
SELECT q.user_id, q.email, q.giveaway_opt_in_at,
       COUNT(q.review_id)::INTEGER AS qualifying_review_count,
       LEAST(COUNT(q.review_id), s.giveaway_max_entries)::INTEGER AS total_entries
FROM qualifying_reviews AS q
CROSS JOIN settings AS s
GROUP BY q.user_id, q.email, q.giveaway_opt_in_at, s.giveaway_max_entries
HAVING COUNT(q.review_id) > 0
ORDER BY total_entries DESC, q.giveaway_opt_in_at ASC;
`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const saved = readFileSync(new URL("../supabase/queries/giveaway_entry_counts.sql", import.meta.url), "utf8");
    if (saved !== sql) throw new Error("Draw SQL differs from the shared giveaway definition. Regenerate it.");
    console.log("Draw SQL matches the shared giveaway definition.");
  } else {
    console.log(sql.trimEnd());
  }
}
